"""
LightLink - Écrit shared/forecast-snapshot.ts: les prévisions du modèle pour un jour réel.

En mode démo (sans Supabase), les apps affichent ces prévisions au lieu d'un scénario inventé.
Jour retenu: le 16 octobre 2026, où l'ECG avait annoncé une coupure partielle à Madina; les
autres quartiers montrent leur taux de base. En mode connecté, les apps lisent la table
predictions, remplie chaque jour par le workflow « Daily data import ».

    python3 prediction/build_forecast_snapshot.py
"""

import json
from datetime import date
from pathlib import Path

from lightlink_model import iso_utc, predict_all

DAY = date(2026, 10, 16)
OUTPUT = Path(__file__).resolve().parent.parent / "shared" / "forecast-snapshot.ts"


def render(day: date = DAY) -> str:
    predictions, _ = predict_all(day)
    rows = [
        {
            "zone_id": p.zone_id,
            "window_start": iso_utc(p.window_start),
            "window_end": iso_utc(p.window_end),
            "probability": p.probability,
            "confidence": p.confidence,
            "expected_duration_min": p.expected_duration_min,
            "hourly_risks": p.hourly_risks,
            "basis": p.basis,
        }
        for p in predictions
    ]
    # Written in Prettier's style, so the format check of the apps accepts the generated file.
    body = "".join(
        "  {\n"
        + "".join(f"    {key}: {json.dumps(value, ensure_ascii=False, separators=(', ', ': '))},\n" for key, value in row.items())
        + "  },\n"
        for row in rows
    )
    return (
        "// Generated by prediction/build_forecast_snapshot.py from data/: do not edit by hand.\n"
        f"// Rules model output for {day.isoformat()}, shown by the apps in demo mode.\n"
        'import type { PredictionRow } from "./forecast";\n\n'
        f'export const snapshotDay = "{day.isoformat()}";\n\n'
        f"export const snapshotPredictions: PredictionRow[] = [\n{body}];\n"
    )


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"Écrit: {OUTPUT}")
